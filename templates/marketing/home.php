<script>
(function() {
    var overlay = document.getElementById('cvViewerOverlay');
    var img = document.getElementById('cvViewerImg');
    var titleEl = document.getElementById('cvViewerTitle');
    var pageInfo = document.getElementById('cvViewerPageInfo');
    var dotsEl = document.getElementById('cvViewerDots');
    var pageWrap = document.getElementById('cvViewerPageWrap');
    var zoomLevelEl = document.getElementById('cvZoomLevel');
    var basePath = '<?= APP_URL ?>/assets/images/cv-examples/';
    var currentSlug = '', totalPages = 0, currentPage = 1;

    // Zoom state
    var zoomSteps = [0.5, 0.75, 1, 1.25, 1.5, 2, 2.5, 3];
    var zoomIndex = 2; // starts at 100%
    var isPanning = false, panStartX = 0, panStartY = 0, scrollStartX = 0, scrollStartY = 0;

    function getZoom() { return zoomSteps[zoomIndex]; }

    function applyZoom() {
        var z = getZoom();
        img.style.transform = 'scale(' + z + ')';
        img.style.transformOrigin = 'top center';
        zoomLevelEl.textContent = Math.round(z * 100) + '%';
        pageWrap.classList.toggle('mk-cv-zoomed', z > 1);
        // If zoomed in, allow scrolling; cursor changes via CSS
    }

    function zoomIn() {
        if (zoomIndex < zoomSteps.length - 1) { zoomIndex++; applyZoom(); }
    }
    function zoomOut() {
        if (zoomIndex > 0) { zoomIndex--; applyZoom(); }
    }
    function zoomReset() {
        zoomIndex = 2;
        applyZoom();
        pageWrap.scrollTop = 0;
        pageWrap.scrollLeft = 0;
    }

    function open(slug, pages, name) {
        currentSlug = slug;
        totalPages = pages;
        currentPage = 1;
        titleEl.textContent = name;
        zoomReset();
        renderDots();
        showPage(1);
        overlay.style.display = 'flex';
        document.body.style.overflow = 'hidden';
    }

    function close() {
        overlay.style.display = 'none';
        document.body.style.overflow = '';
        zoomReset();
    }

    function showPage(n) {
        currentPage = Math.max(1, Math.min(n, totalPages));
        img.src = basePath + currentSlug + '-page-' + currentPage + '.webp';
        img.alt = titleEl.textContent + ' page ' + currentPage;
        pageInfo.textContent = currentPage + ' / ' + totalPages;
        updateDots();
        // Reset scroll position on page change but keep zoom level
        pageWrap.scrollTop = 0;
        pageWrap.scrollLeft = 0;
    }

    function renderDots() {
        dotsEl.innerHTML = '';
        for (var i = 1; i <= totalPages; i++) {
            var dot = document.createElement('button');
            dot.className = 'mk-cv-dot' + (i === 1 ? ' active' : '');
            dot.setAttribute('aria-label', 'Page ' + i);
            dot.dataset.page = i;
            dotsEl.appendChild(dot);
        }
    }

    function updateDots() {
        dotsEl.querySelectorAll('.mk-cv-dot').forEach(function(d) {
            d.classList.toggle('active', parseInt(d.dataset.page) === currentPage);
        });
    }

    // Cover clicks
    document.querySelectorAll('.mk-cv-cover').forEach(function(cover) {
        cover.addEventListener('click', function() {
            open(this.dataset.slug, parseInt(this.dataset.pages), this.dataset.name);
        });
        cover.addEventListener('keydown', function(e) {
            if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); this.click(); }
        });
    });

    // Controls
    document.getElementById('cvViewerClose').addEventListener('click', close);
    overlay.addEventListener('click', function(e) { if (e.target === overlay) close(); });
    document.getElementById('cvPrev').addEventListener('click', function() { showPage(currentPage - 1); });
    document.getElementById('cvNext').addEventListener('click', function() { showPage(currentPage + 1); });
    dotsEl.addEventListener('click', function(e) {
        if (e.target.classList.contains('mk-cv-dot')) showPage(parseInt(e.target.dataset.page));
    });

    // Zoom controls
    document.getElementById('cvZoomIn').addEventListener('click', zoomIn);
    document.getElementById('cvZoomOut').addEventListener('click', zoomOut);
    document.getElementById('cvZoomReset').addEventListener('click', zoomReset);

    // Double-click to toggle zoom
    img.addEventListener('dblclick', function(e) {
        e.preventDefault();
        if (getZoom() > 1) {
            zoomReset();
        } else {
            zoomIndex = 5; // jump to 2x
            applyZoom();
        }
    });

    // Mouse wheel zoom
    pageWrap.addEventListener('wheel', function(e) {
        if (!e.ctrlKey) return;
        e.preventDefault();
        if (e.deltaY < 0) zoomIn();
        else zoomOut();
    }, {passive: false});

    // Mouse drag to pan when zoomed
    pageWrap.addEventListener('mousedown', function(e) {
        if (getZoom() <= 1) return;
        isPanning = true;
        panStartX = e.clientX;
        panStartY = e.clientY;
        scrollStartX = pageWrap.scrollLeft;
        scrollStartY = pageWrap.scrollTop;
        pageWrap.style.cursor = 'grabbing';
        e.preventDefault();
    });
    document.addEventListener('mousemove', function(e) {
        if (!isPanning) return;
        pageWrap.scrollLeft = scrollStartX - (e.clientX - panStartX);
        pageWrap.scrollTop = scrollStartY - (e.clientY - panStartY);
    });
    document.addEventListener('mouseup', function() {
        if (isPanning) {
            isPanning = false;
            pageWrap.style.cursor = '';
        }
    });

    // Keyboard navigation
    document.addEventListener('keydown', function(e) {
        if (overlay.style.display !== 'flex') return;
        if (e.key === 'Escape') close();
        if (e.key === 'ArrowLeft') showPage(currentPage - 1);
        if (e.key === 'ArrowRight') showPage(currentPage + 1);
        if (e.key === '+' || e.key === '=') { e.preventDefault(); zoomIn(); }
        if (e.key === '-') { e.preventDefault(); zoomOut(); }
        if (e.key === '0') { e.preventDefault(); zoomReset(); }
    });

    // Touch: swipe to navigate, pinch to zoom
    var touchStartX = 0, touchStartDist = 0, pinching = false;
    var viewerBody = document.querySelector('.mk-cv-viewer-body');

    function getTouchDist(touches) {
        var dx = touches[0].clientX - touches[1].clientX;
        var dy = touches[0].clientY - touches[1].clientY;
        return Math.sqrt(dx * dx + dy * dy);
    }

    if (viewerBody) {
        viewerBody.addEventListener('touchstart', function(e) {
            if (e.touches.length === 2) {
                pinching = true;
                touchStartDist = getTouchDist(e.touches);
            } else if (e.touches.length === 1 && getZoom() <= 1) {
                touchStartX = e.changedTouches[0].screenX;
            }
        }, {passive: true});

        viewerBody.addEventListener('touchmove', function(e) {
            if (pinching && e.touches.length === 2) {
                var dist = getTouchDist(e.touches);
                var ratio = dist / touchStartDist;
                if (ratio > 1.15) { touchStartDist = dist; zoomIn(); }
                else if (ratio < 0.85) { touchStartDist = dist; zoomOut(); }
            }
        }, {passive: true});

        viewerBody.addEventListener('touchend', function(e) {
            if (pinching) {
                if (e.touches.length < 2) pinching = false;
                return;
            }
            if (getZoom() > 1) return; // don't swipe pages when zoomed
